-- Falko initial schema
-- Run this against a fresh Postgres database (Supabase or other)
--
-- It creates all the tables used by the application in the correct order
-- so that foreign key references are satisfied.
--
-- Before running, make sure the following extensions are available:
--   uuid-ossp  (for uuid_generate_v4)
--   pgcrypto   (for gen_random_uuid)
--
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS pgcrypto;

