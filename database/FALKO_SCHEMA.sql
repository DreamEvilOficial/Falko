CREATE TABLE public.tiendas (
  id uuid NOT NULL DEFAULT uuid_generate_v4(),
  nombre character varying NOT NULL,
  slug character varying NOT NULL UNIQUE,
  descripcion text,
  logo_url text,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  activo boolean DEFAULT true,
  mp_public_key character varying,
  mp_access_token character varying,
  mp_cvu character varying,
  whatsapp character varying,
  instagram character varying,
  email character varying,
  direccion text,
  moneda character varying DEFAULT 'ARS'::character varying,
  timezone character varying DEFAULT 'America/Argentina/Buenos_Aires'::character varying,
  CONSTRAINT tiendas_pkey PRIMARY KEY (id)
);

